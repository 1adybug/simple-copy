use tauri::AppHandle;

use crate::model::{Formats, Payload, WriteId, file_uri};

#[cfg(windows)]
mod windows;
#[cfg(windows)]
pub use windows::{Monitor, Native, Target, capture_target, enable_win_v, start_monitor};

#[cfg(not(windows))]
mod desktop;
#[cfg(not(windows))]
pub use desktop::{Monitor, Native, Target, capture_target, enable_win_v, start_monitor};

pub const ORIGIN_FORMAT: &str = "io.simplecopy.write-origin";

pub type Wake = Arc<dyn Fn() + Send + Sync>;

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Capabilities {
    pub platform: &'static str,
    pub background: bool,
    pub automatic_paste: bool,
    pub restore_available: bool,
    pub can_authorize: bool,
    pub message: Option<String>,
}

pub struct Capture {
    pub revision: u64,
    pub payload: Payload,
    pub origin: Option<WriteId>,
}

pub enum Written {
    Applied(u64),
    Superseded,
}

pub trait ClipboardBackend: Send {
    fn capabilities(&self) -> Capabilities;
    fn revision(&self) -> Result<u64, String>;
    fn read(&self, formats: &Formats) -> Result<Capture, String>;
    fn write(
        &self,
        payload: &Payload,
        expected: Option<u64>,
        origin: WriteId,
    ) -> Result<Written, String>;
    fn paste(&self, target: &Target, expected: u64) -> Result<bool, String>;
}

pub fn create(app: AppHandle) -> Result<Box<dyn ClipboardBackend>, String> {
    Native::new(app).map(|native| Box::new(native) as Box<dyn ClipboardBackend>)
}

pub fn read_payload(
    ctx: &ClipboardContext,
    formats: &Formats,
) -> Result<(Payload, Option<WriteId>), String> {
    let offered = ctx
        .available_formats()
        .map_err(|_| "剪贴板正忙，请稍后重试。".to_string())?;
    let origin = ctx
        .get_buffer(ORIGIN_FORMAT)
        .ok()
        .and_then(|bytes| bytes.try_into().ok());
    let confidential = offered.iter().any(|format| {
        matches!(
            format.as_str(),
            "ExcludeClipboardContentFromMonitorProcessing"
                | "org.nspasteboard.ConcealedType"
                | "org.nspasteboard.TransientType"
                | "org.nspasteboard.AutoGeneratedType"
        )
    }) || ctx
        .get_buffer("CanIncludeInClipboardHistory")
        .ok()
        .is_some_and(|bytes| bytes.get(..4) == Some(&[0, 0, 0, 0]));
    if confidential {
        return Ok((Payload::default(), origin));
    }
    if ctx.has(ContentFormat::Files) {
        let files = ctx
            .get_files()
            .map_err(|_| "无法读取剪贴板文件引用。".to_string())?
            .iter()
            .filter_map(|file| file_uri(file))
            .collect();
        return Ok((
            Payload {
                files,
                ..Payload::default()
            },
            origin,
        ));
    }
    let mut payload = Payload::default();
    if (formats.text || formats.link) && ctx.has(ContentFormat::Text) {
        payload.text = Some(
            ctx.get_text()
                .map_err(|_| "无法读取剪贴板文字。".to_string())?,
        );
    }
    if formats.rich_text {
        if ctx.has(ContentFormat::Html) {
            payload.html = Some(
                ctx.get_html()
                    .map_err(|_| "无法读取剪贴板 HTML。".to_string())?,
            );
        }
        if ctx.has(ContentFormat::Rtf) {
            #[cfg(windows)]
            let rtf_type = "Rich Text Format";
            #[cfg(target_os = "macos")]
            let rtf_type = "public.rtf";
            #[cfg(target_os = "linux")]
            let rtf_type = "text/rtf";
            payload.rtf = Some(
                ctx.get_buffer(rtf_type)
                    .map_err(|_| "无法读取剪贴板 RTF。".to_string())?,
            );
        }
    }
    if formats.image && ctx.has(ContentFormat::Image) {
        let image = ctx
            .get_image()
            .map_err(|_| "无法读取剪贴板图片。".to_string())?;
        let (width, height) = image.get_size();
        if width > 12_000 || height > 12_000 {
            return Err("图片尺寸超过 12000 × 12000。".into());
        }
        payload.png = Some(
            image
                .to_png()
                .map_err(|_| "无法转换剪贴板图片。".to_string())?
                .get_bytes()
                .to_vec(),
        );
    }
    Ok((payload, origin))
}

pub fn validate_files(payload: &Payload) -> Result<(), String> {
    for uri in &payload.files {
        let path = url::Url::parse(uri)
            .ok()
            .and_then(|url| url.to_file_path().ok())
            .ok_or_else(|| "文件引用格式无效。".to_string())?;
        if !path.exists() {
            return Err(format!("原文件已移动或删除：{}", path.display()));
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_missing_file_is_rejected_before_clipboard_writes() {
        let missing =
            std::env::temp_dir().join(format!("simple-copy-missing-file-{}", std::process::id()));
        let payload = Payload {
            files: vec![url::Url::from_file_path(missing).unwrap().into()],
            ..Payload::default()
        };
        assert!(validate_files(&payload).is_err());
    }
}
